export function photoSrc(key: PhotoKey, variant = 1): string {
  return variant <= 1 ? `/photos/${key}.jpg` : `/photos/${key}-${variant}.jpg`;
}

export function photoAlt(key: PhotoKey): string {
  return ALT[key];
}

/**
 * Picks the photo key for a club: college first, then the first category with
 * a specific (non-"community") photo, then the generic pool. A club tagged
 * "Special Interest, Engineering" gets engineering, and Solar Car gets
 * engineering rather than the cornfield its first category implies.
 */
function keyForClub(club: { college: string; categories: string[] }): PhotoKey {
  const fromCollege = COLLEGE_PHOTO[club.college];
  if (fromCollege) return fromCollege;

  for (const category of club.categories) {
    const key = CATEGORY_PHOTO[category];
    if (key && key !== "community") return key;
  }

  return "community";
}

/**
 * Full photo pick for a club: which pool, and which member of that pool.
 * The variant is hashed from the slug so it's stable across renders and
 * across pages (a club always shows the same photo everywhere it appears),
 * while different clubs sharing a pool spread across its variants.
 */
export function photoForClub(club: {
  slug: string;
  name?: string;
  college: string;
  categories: string[];
  greek?: { photo: string | null };
}): {
  key: PhotoKey;
  variant: number;
  src: string;
  alt: string;
  own: boolean;
  quality: number;
  /** "identity" is typeset name artwork: no photo gradient, never a chapter photo. */
  kind: "cover" | "photo" | "identity" | "stock";
} {
  if (CLUB_COVER_SET.has(club.slug)) {
    return {
      key: keyForClub(club),
      variant: 0,
      src: `/photos/clubs/${club.slug}.jpg`,
      alt: club.name ? `Watercolor illustration for ${club.name}` : "Club illustration",
      own: true,
      // Watercolor wash and paper grain break up badly at Next's default 75,
      // so covers are served at 90 (allowed in next.config.ts images.qualities).
      quality: 90,
      kind: "cover",
    };
  }
  // Greek chapters use the photo they posted on their SFE page. Chapters
  // without one use the generic pool, never "culture": that pool shows
  // performers in regalia, which reads wrong for a fraternity or sorority.
  if (club.greek?.photo) {
    return {
      key: "community",
      variant: 0,
      src: club.greek.photo,
      alt: club.name ? `${club.name} at Iowa State` : "Chapter photo",
      own: true,
      quality: 75,
      kind: "photo",
    };
  }
  const identity = GREEK_IDENTITY[club.slug];
  if (identity) {
    return {
      key: "community",
      variant: 0,
      src: identity.src,
      alt: identity.alt,
      own: false,
      quality: 90,
      kind: "identity",
    };
  }
  const key = club.greek ? "community" : keyForClub(club);
  const size = POOL_SIZE[key];
  const variant = (hash(club.slug) % size) + 1;
  return {
    key,
    variant,
    src: photoSrc(key, variant),
    alt: photoAlt(key),
    own: false,
    quality: 75,
    kind: "stock",
  };
}

