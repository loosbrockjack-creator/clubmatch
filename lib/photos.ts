const CLUB_COVER_SET = new Set(CLUB_COVERS);

/** Small deterministic string hash (djb2), used to pick a stable pool index. */
function hash(input: string): number {
  let h = 5381;
  for (let i = 0; i < input.length; i++) {
    h = (h * 33) ^ input.charCodeAt(i);
  }
  return h >>> 0;
}

