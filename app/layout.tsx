import "./globals.css";

const inter = Inter({
  subsets: ["latin"],
  variable: "--font-inter",
  display: "swap",
});

// Iowa State sets headlines in a Caslon-family serif. Source Serif 4 is the
// closest open equivalent, and carries the same institutional weight.
